//! Compiles ScreenScraper's developer credentials into the official builds without ever writing
//! them in clear: they come from the environment at build time (CI secrets
//! BORNE_SS_DEV_ID / BORNE_SS_DEV_PASSWORD, never in the repository) and are stored masked with a
//! key drawn for each build, so they appear neither in the source nor as readable strings in the
//! binary. Builds without them simply have no ScreenScraper developer access.

use std::io::Write;

fn mask(name: &str, value: &str, seed: &mut u64, out: &mut String) {
    let mut key = Vec::with_capacity(value.len());
    for _ in 0..value.len() {
        // xorshift64*
        *seed ^= *seed >> 12;
        *seed ^= *seed << 25;
        *seed ^= *seed >> 27;
        key.push((seed.wrapping_mul(0x2545F4914F6CDD1D) >> 56) as u8);
    }
    let data: Vec<u8> = value.bytes().zip(&key).map(|(b, k)| b ^ k).collect();
    out.push_str(&format!("pub const {name}: (&[u8], &[u8]) = (&{data:?}, &{key:?});\n"));
}

fn main() {
    println!("cargo:rerun-if-env-changed=BORNE_SS_DEV_ID");
    println!("cargo:rerun-if-env-changed=BORNE_SS_DEV_PASSWORD");
    let id = std::env::var("BORNE_SS_DEV_ID").unwrap_or_default();
    let password = std::env::var("BORNE_SS_DEV_PASSWORD").unwrap_or_default();
    let mut seed = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos() as u64)
        .unwrap_or(0x9E3779B97F4A7C15)
        ^ ((std::process::id() as u64) << 32)
        | 1;
    let mut out = String::from("// Generated by build.rs: masked ScreenScraper developer credentials.\n");
    mask("SS_DEV_ID", id.trim(), &mut seed, &mut out);
    mask("SS_DEV_PASSWORD", password.trim(), &mut seed, &mut out);
    let path = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("ss_dev.rs");
    std::fs::File::create(path).unwrap().write_all(out.as_bytes()).unwrap();
}
